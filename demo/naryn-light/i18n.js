  var cur = "ru", subs = [], miss = {};
  var VOL = /^(\d+(?:,\d+)?) (мл|л)$/;

  function pick(a, ru) {
    if (cur === "ru" || !a) return ru;
    var v = a[X[cur]];
    return v == null ? ru : v;
  }
  function t(key, vars) {
    var a = S[key];
    if (!a) return key;
    var s = a[LANGS.indexOf(cur)];
    if (s == null) s = a[0];
    return vars ? s.replace(/\{(\w+)\}/g, function (m, k) { return k in vars ? vars[k] : m; }) : s;
  }
  function note(s) { if (cur !== "ru") miss[s] = 1; }
  function menu(ru) {
    if (cur === "ru") return ru;
    if (!M[ru]) { note(ru); return ru; }
    return pick(M[ru], ru);
  }
  function word(s) {
    if (W[s]) return pick(W[s], s);
    var v = VOL.exec(s);
    if (v) {
      if (cur === "kk") return s;
      var n = v[1].replace(",", ".");
      if (cur === "zh") return n + (v[2] === "мл" ? "毫升" : "升");
      return n + (v[2] === "мл" ? " ml" : " L");
    }
    note(s);
    return s;
  }
  function words(ru) {
    if (cur === "ru" || !ru) return ru;
    if (W[ru] || VOL.test(ru)) return word(ru);
    return ru.split(/(, |; | \/ )/).map(function (p, i) {
      if (i % 2) return cur === "zh" ? ({ ", ": "、", "; ": "；" }[p] || p) : p;
      return word(p);
    }).join("");
  }

